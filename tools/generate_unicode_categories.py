#!/usr/bin/env python3
"""Generate deterministic Unicode category intervals for the native tokenizer.

The generated table keeps Unicode-aware pre-tokenization independent of the host
locale and operating system. Run this script only when deliberately updating the
documented Unicode database version.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import tempfile
import unicodedata


CATEGORIES = ("L", "M", "N", "P", "S", "Z")


def intervals(prefix: str) -> list[tuple[int, int]]:
    result: list[tuple[int, int]] = []
    start: int | None = None
    previous = 0
    for codepoint in range(0x110000):
        matches = unicodedata.category(chr(codepoint)).startswith(prefix)
        if matches and start is None:
            start = previous = codepoint
        elif matches:
            previous = codepoint
        elif start is not None:
            result.append((start, previous))
            start = None
    if start is not None:
        result.append((start, previous))
    return result


def render() -> str:
    lines = [
        "// Generated by tools/generate_unicode_categories.py; do not edit manually.",
        f'// Python unicodedata version: {unicodedata.unidata_version}',
        "struct UnicodeRange { std::uint32_t first; std::uint32_t last; };",
        "",
    ]
    for prefix in CATEGORIES:
        values = intervals(prefix)
        lines.append(f"constexpr std::array<UnicodeRange, {len(values)}> kUnicode{prefix}Ranges{{{{")
        for first, last in values:
            lines.append(f"    {{0x{first:05x}U, 0x{last:05x}U}},")
        lines.extend(("}};", ""))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "src" / "inference" / "unicode_categories.inc",
    )
    args = parser.parse_args()
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    content = render()
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", newline="\n", dir=output.parent, delete=False
    ) as temporary:
        temporary.write(content)
        temporary_path = Path(temporary.name)
    os.replace(temporary_path, output)
    print(f"wrote {output} ({len(content.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
